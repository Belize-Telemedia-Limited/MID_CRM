  VV_COD_SYSTEM NUMBER;
  VV_COD_ORGANIZATION VARCHAR2(100) := 'SFCRM';
  VV_NM_ORGANIZATION VARCHAR2(100) :=  'Salesforce';
  VV_DSC_ORGANIZATION VARCHAR2(100) := 'Agentic CRM';
  VV_TP_STATUS_ORGANIZATION VARCHAR2(1) := 'A';
