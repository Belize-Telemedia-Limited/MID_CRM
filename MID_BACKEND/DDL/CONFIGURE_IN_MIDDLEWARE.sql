--1.1 MID_PACKAGE(SYSTEM) INSERT
--CREATE SYSTEM INFORMATION INTO THE MIDDLEWARE FOR LOGGING PURPOSES
DECLARE

  VV_COD_SYSTEM NUMBER; --set to default
  VV_NM_SYSTEM VARCHAR2(100) := 'CRM';
  VV_DSC_SYSTEM VARCHAR2(100) := 'SALESFORCE INTEGRATION';
  VV_TP_STATUS_SYSTEM VARCHAR2(1) := 'A';
  
BEGIN
  SELECT COUNT(*) INTO VV_COD_SYSTEM FROM MID_SYSTEM WHERE UPPER(NM_SYSTEM) = UPPER(VV_NM_SYSTEM);
  
  IF VV_COD_SYSTEM = 0 THEN
  
      SELECT MAX(COD_SYSTEM)+1 INTO VV_COD_SYSTEM FROM MID_SYSTEM;
      INSERT INTO MID_SYSTEM (COD_SYSTEM, NM_SYSTEM, DSC_SYSTEM, TP_STATUS_SYSTEM)
      VALUES (VV_COD_SYSTEM, VV_NM_SYSTEM, VV_DSC_SYSTEM, VV_TP_STATUS_SYSTEM);
      COMMIT;
      DBMS_OUTPUT.PUT_LINE('INSERT INTERFACE SYSTEM: '||VV_COD_SYSTEM||'|'||VV_NM_SYSTEM||'|'||VV_DSC_SYSTEM||'|'||VV_TP_STATUS_SYSTEM);
      
  ELSE
  
    SELECT COD_SYSTEM INTO VV_COD_SYSTEM FROM MID_SYSTEM WHERE UPPER(NM_SYSTEM) = UPPER(VV_NM_SYSTEM);
    DBMS_OUTPUT.PUT_LINE('ISSUE INSERTING SYSTEM BELOW');
    DBMS_OUTPUT.PUT_LINE('INTERFACE SYSTEM: '||VV_COD_SYSTEM||'|'||VV_NM_SYSTEM||'|'||VV_DSC_SYSTEM||'|'||VV_TP_STATUS_SYSTEM);
    
  END IF;
  
END;
