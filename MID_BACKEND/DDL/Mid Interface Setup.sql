DECLARE

  VV_COD_SYSTEM NUMBER; --set to default
  VV_NM_SYSTEM VARCHAR2(100) := 'DIGI_GO';
  VV_DSC_SYSTEM VARCHAR2(100) := 'DIGI GO CUSTOMER PORTAL SYSTEM';
  VV_TP_STATUS_SYSTEM VARCHAR2(1) := 'A';  
  
  VV_COD_ORGANIZATION VARCHAR2(100) := 'BTL';
  VV_NM_ORGANIZATION VARCHAR2(100) :=  'Belize Telemedia Ltd.';
  VV_DSC_ORGANIZATION VARCHAR2(100) := 'better than SMART';
  VV_TP_STATUS_ORGANIZATION VARCHAR2(1) := 'A';
  VV_DSC_INTERFACE VARCHAR2(500);
  VV_INTERFACE_EXISTS NUMBER;
  VV_INTERFACE_ID NUMBER := 0;
  VV_FL_LOG NUMBER := 0;
BEGIN
	BEGIN
	  SELECT COUNT(*) INTO VV_COD_SYSTEM FROM MID_SYSTEM WHERE UPPER(NM_SYSTEM) = UPPER(VV_NM_SYSTEM);
	  
	  IF VV_COD_SYSTEM = 0 THEN
	  
		  SELECT MAX(COD_SYSTEM)+1 INTO VV_COD_SYSTEM FROM MID_SYSTEM;
		  INSERT INTO MID_SYSTEM (COD_SYSTEM, NM_SYSTEM, DSC_SYSTEM, TP_STATUS_SYSTEM)
		  VALUES (VV_COD_SYSTEM, VV_NM_SYSTEM, VV_DSC_SYSTEM, VV_TP_STATUS_SYSTEM);
		  COMMIT;
		  DBMS_OUTPUT.PUT_LINE('INSERT INTERFACE SYSTEM: '||VV_COD_SYSTEM||'|'||VV_NM_SYSTEM||'|'||VV_DSC_SYSTEM||'|'||VV_TP_STATUS_SYSTEM);
		  
	  ELSE
	  
		SELECT COD_SYSTEM INTO VV_COD_SYSTEM FROM MID_SYSTEM WHERE UPPER(NM_SYSTEM) = UPPER(VV_NM_SYSTEM);
		DBMS_OUTPUT.PUT_LINE('ISSUE INSERTING SYSTEM BELOW');
		DBMS_OUTPUT.PUT_LINE('INTERFACE SYSTEM: '||VV_COD_SYSTEM||'|'||VV_NM_SYSTEM||'|'||VV_DSC_SYSTEM||'|'||VV_TP_STATUS_SYSTEM);
		
	  END IF;
	  
	END;

	--1.2 MID_INTERFACE INSERT
	BEGIN

		Select COD_SYSTEM into VV_COD_SYSTEM from mid_system where nm_system = VV_NM_SYSTEM;   

		FOR R_INTERFACE IN
        ( 
            SELECT * FROM MID_INTERFACE@MIDDB WHERE COD_SYSTEM = (SELECT COD_SYSTEM FROM MID_SYSTEM@MIDDB WHERE UPPER(NM_SYSTEM) = UPPER(VV_NM_SYSTEM))
        )
		Loop

			Select count(*) into VV_INTERFACE_EXISTS from mid_interface mi where cod_system = VV_COD_SYSTEM and nm_interface = R_INTERFACE.nm_interface;
                DBMS_OUTPUT.PUT_LINE('Interface attempt: '||VV_INTERFACE_ID||'|'||R_INTERFACE.nm_interface||'|'||R_INTERFACE.dsc_interface||'|GV_CODSYSTEM:'||VV_COD_SYSTEM||'|'||VV_INTERFACE_EXISTS ); 

			if (VV_INTERFACE_EXISTS = 0) THEN
				Select max(id_interface)+1 into VV_INTERFACE_ID from mid_interface mi;
				Insert into mid_interface mi values (VV_INTERFACE_ID, R_INTERFACE.nm_interface, R_INTERFACE.dsc_interface, VV_COD_SYSTEM,'Y'); 
                COMMIT;
				DBMS_OUTPUT.PUT_LINE('Interface Inserted: '||VV_INTERFACE_ID||'|'||R_INTERFACE.nm_interface||'|'||R_INTERFACE.dsc_interface||'|GV_CODSYSTEM:'||VV_COD_SYSTEM||'|'||'Y' ); 
			ELSE
                UPDATE MID_INTERFACE MI SET DSC_INTERFACE = R_INTERFACE.DSC_INTERFACE WHERE UPPER(NM_INTERFACE) = UPPER(R_INTERFACE.nm_interface) AND COD_SYSTEM = VV_COD_SYSTEM;
                COMMIT;
                DBMS_OUTPUT.PUT_LINE('INTERFACE UPDATE: '||VV_INTERFACE_ID||'|'||R_INTERFACE.nm_interface||'|'||VV_DSC_INTERFACE||'|GV_CODSYSTEM:'
                                    ||VV_COD_SYSTEM
                                    ||'|'
                                    ||VV_FL_LOG);
			END IF;  
		End Loop;
		commit;

	End;

	--1.3 MID_ORGANIZATION INSERT
	BEGIN
	  SELECT COUNT(*) INTO VV_COD_SYSTEM FROM MID_ORGANIZATION@middb WHERE UPPER(COD_ORGANIZATION) = UPPER(VV_COD_ORGANIZATION);
	  IF VV_COD_SYSTEM = 0 THEN
		  INSERT INTO "MIDWARE"."MID_ORGANIZATION" (COD_ORGANIZATION, NM_ORGANIZATION, DSC_ORGANIZATION, TP_STATUS_ORGANIZATION)
		  VALUES (VV_COD_ORGANIZATION, VV_NM_ORGANIZATION, VV_DSC_ORGANIZATION, VV_TP_STATUS_ORGANIZATION);
		  COMMIT;
		  DBMS_OUTPUT.PUT_LINE('INSERTED ORGANIZATION: '||VV_COD_ORGANIZATION||'|'||VV_NM_ORGANIZATION||'|'||VV_DSC_ORGANIZATION||'|'||VV_TP_STATUS_ORGANIZATION);
	  ELSE
		DBMS_OUTPUT.PUT_LINE('ISSUE INSERTING ORGANIZATION BELOW');
		DBMS_OUTPUT.PUT_LINE('ORGANIZATION: '||VV_COD_ORGANIZATION||'|'||VV_NM_ORGANIZATION||'|'||VV_DSC_ORGANIZATION||'|'||VV_TP_STATUS_ORGANIZATION);
	  END IF;
	END;
End;
/
select * FROM MID_SYSTEM WHERE UPPER(NM_SYSTEM) = UPPER('DIGI_GO');
