--1.4 MID_USER INSERT
--INSERT USER MID USER FOR AUTHENTICATION AND LOGGING
DECLARE
  VV_ID_USER NUMBER;
  VV_NM_USER VARCHAR2(100) := 'SFCRM';
  VV_DSC_USER VARCHAR2(100) := 'SalesForceUser';
  VV_COD_ORGANIZATION VARCHAR2(100) := 'SFCRM';
  VV_TP_STATUS_SYSTEM VARCHAR2(1) := 'A';
  VV_PW_USER VARCHAR2(50) := 'SFCRM';
BEGIN
  SELECT COUNT(*) INTO VV_ID_USER FROM MID_USER WHERE UPPER(NM_USER) = UPPER(VV_NM_USER);
  IF VV_ID_USER = 0 THEN
    SELECT MAX(ID_USER)+1 INTO VV_ID_USER FROM MID_USER;
    INSERT INTO MIDWARE.MID_USER (ID_USER, NM_USER, DSC_USER, COD_ORGANIZATION, TP_STATUS_USER, PW_USER)
    VALUES (VV_ID_USER, UPPER(VV_NM_USER), VV_DSC_USER, VV_COD_ORGANIZATION, VV_TP_STATUS_SYSTEM, pck_security.get_hash(UPPER(VV_NM_USER),VV_PW_USER));
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('INSERTED USER: '||VV_ID_USER||'|'||UPPER(VV_NM_USER)||'|'||VV_DSC_USER||'|'||VV_COD_ORGANIZATION||'|'||VV_TP_STATUS_SYSTEM);
  ELSE
    UPDATE MID_USER SET DSC_USER = VV_DSC_USER, PW_USER = PCK_SECURITY.GET_HASH(UPPER(VV_NM_USER),VV_PW_USER), TP_STATUS_USER = VV_TP_STATUS_SYSTEM WHERE UPPER(NM_USER) = UPPER(VV_NM_USER);
    DBMS_OUTPUT.PUT_LINE('UPDATING USER:'||UPPER(VV_NM_USER)||'|'||VV_DSC_USER||'|'||VV_COD_ORGANIZATION||'|'||VV_TP_STATUS_SYSTEM||'|'||VV_PW_USER||'('||PCK_SECURITY.GET_HASH(UPPER(VV_NM_USER),VV_PW_USER)||')');
  END IF;
  EXCEPTION WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Contact BTL MIDWARE ADMIN');
    DBMS_OUTPUT.PUT_LINE(to_char($$PLSQL_LINE)||': '||DBMS_UTILITY.FORMAT_ERROR_STACK||DBMS_UTILITY.FORMAT_CALL_STACK||DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
END;
